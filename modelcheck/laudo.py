def _texto_problema(chave: str, lang="pt") -> str:
    """
    Traduz o código interno para uma frase. Se aparecer um código novo sem
    tradução, devolve algo legível em vez de vazar o identificador cru —
    foi assim que "Ood only" chegou a um laudo.
    """
    chave = str(chave or "")
    tabela = _PROBLEMA if lang == "pt" else _PROBLEMA_EN
    if chave in tabela:
        return tabela[chave]
    t = _T[lang if lang in _T else "pt"]
    limpo = chave.replace("_ONLY", "").replace("_", " ").strip().lower()
    return t["sinal"].format(x=limpo) if limpo else t["sem_problema"]

